#!/usr/bin/env python3
"""almanac_fixture.py — Skyfield's rise / set / transit times, the oracle for
SkyCore's Almanac and satellite pass finder.

Same conventions on both sides: airless (geometric) topocentric altitude of
the centre, crossing the standard horizon (-0.8333° for the Sun and Moon,
-0.5667° for points), transits as altitude maxima. Satellites: rise and set
at 0°, culmination as the maximum, from the OMM records in satellites.json.

  tools/oracle/.venv/bin/python tools/oracle/almanac_fixture.py

Writes SkyCore/Tests/SkyCoreTests/Fixtures/almanac.json.
"""
import datetime as dt, json, os
from sgp4.api import Satrec
from sgp4 import omm
from skyfield import almanac
from skyfield.api import EarthSatellite, Loader, wgs84
from skyfield.searchlib import find_discrete, find_maxima

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CACHE = os.path.expanduser('~/.cache/ducktyping-sky')
FIX = os.path.join(ROOT, 'SkyCore', 'Tests', 'SkyCoreTests', 'Fixtures')

load = Loader(CACHE)
ts = load.timescale()
eph = load('de421.bsp')
earth = eph['earth']

PLACES = [('Stevens Point', 44.5236, -89.5746, 330), ('Sydney', -33.8688, 151.2093, 20),
          ('Tromso', 69.6492, 18.9553, 10)]
DAYS = ['2026-01-15', '2026-03-20', '2026-06-21', '2026-10-30', '2027-02-08']
BODIES = {'Sun': 'sun', 'Moon': 'moon', 'Mercury': 'mercury', 'Venus': 'venus', 'Mars': 'mars',
          'Jupiter': 'jupiter barycenter', 'Saturn': 'saturn barycenter',
          'Uranus': 'uranus barycenter', 'Neptune': 'neptune barycenter'}

def iso(t):
    return t.utc_datetime().strftime('%Y-%m-%dT%H:%M:%S.%f')[:-3] + 'Z'

bodies = []
for name, lat, lon, h in PLACES:
    site = wgs84.latlon(lat, lon, elevation_m=h)
    obs = earth + site
    for day in DAYS:
        d = dt.datetime.fromisoformat(day).replace(tzinfo=dt.timezone.utc)
        t0, t1 = ts.from_datetime(d), ts.from_datetime(d + dt.timedelta(days=1))
        for bname, key in BODIES.items():
            target = eph[key]
            horizon = -0.8333 if bname in ('Sun', 'Moon') else -0.5667

            def alt(t):
                return obs.at(t).observe(target).apparent().altaz()[0].degrees
            def up(t):
                return alt(t) > horizon
            up.step_days = 1 / 48
            alt.step_days = 1 / 48
            times, ups = find_discrete(t0, t1, up)
            rises = [iso(t) for t, u in zip(times, ups) if u]
            sets = [iso(t) for t, u in zip(times, ups) if not u]
            mt, mv = find_maxima(t0, t1, alt)
            peaks = [{'t': iso(t), 'alt': float(v)} for t, v in zip(mt, mv)]
            bodies.append({'place': name, 'lat': lat, 'lon': lon, 'height': h, 'start': iso(t0), 'end': iso(t1),
                           'body': bname, 'horizon': horizon, 'rises': rises, 'sets': sets, 'peaks': peaks})

# satellites: the same OMM records the position oracle uses
sat_fix = json.load(open(os.path.join(FIX, 'satellites.json')))
records = sat_fix['elements']
sats = []
name, lat, lon, h = PLACES[0]
site = wgs84.latlon(lat, lon, elevation_m=h)
for rec in records:
    sr = Satrec()
    omm.initialize(sr, rec)
    s = EarthSatellite.from_satrec(sr, ts)
    epoch = s.epoch.utc_datetime()
    t0 = ts.from_datetime(epoch)
    t1 = ts.from_datetime(epoch + dt.timedelta(hours=24))
    times, events = s.find_events(site, t0, t1, altitude_degrees=0.0)
    passes, cur = [], {}
    for t, e in zip(times, events):
        if e == 0:
            cur = {'rise': iso(t)}
        elif e == 1:
            if 'rise' not in cur:
                continue                       # pass already under way at the start
            a = (s - site).at(t).altaz()[0].degrees
            cur.setdefault('peaks', []).append({'t': iso(t), 'alt': float(a)})
        elif e == 2 and 'rise' in cur:
            cur['set'] = iso(t)
            passes.append(cur)
            cur = {}
    sats.append({'id': rec['NORAD_CAT_ID'], 'start': iso(t0), 'end': iso(t1), 'passes': passes})

out = {'note': 'Skyfield 1.55 + DE421; generated by tools/oracle/almanac_fixture.py',
       'place': {'lat': lat, 'lon': lon, 'height': h}, 'bodies': bodies, 'satellites': sats}
json.dump(out, open(os.path.join(FIX, 'almanac.json'), 'w'), indent=1)
print(len(bodies), 'body-days;', sum(len(s['passes']) for s in sats), 'satellite passes')
